assert.match(controls, /data-testid="companion-mode-pet"/, 'Pet icon control needs a stable selector');
assert.match(controls, /data-testid="companion-hide"/, 'Hide must remain separate from mode controls');
assert.match(miniHtml, /companion-mode-mini[\s\S]*data-active="true"/, 'Mini surface must mark Mini active');
assert.match(miniHtml, /companion-mode-pet[\s\S]*data-active="false"/, 'Mini surface must mark Pet inactive');
assert.match(petHtml, /companion-mode-mini[\s\S]*data-active="false"/, 'Pet surface must mark Mini inactive');
assert.match(petHtml, /companion-mode-pet[\s\S]*data-active="true"/, 'Pet surface must mark Pet active');
assert.doesNotMatch(miniHtml, />PET<\/button>/, 'Mini must not use the old text mode button');
assert.match(miniHtml, /<\/main><div class="companion-control-dock">/, 'Mini controls must render below the panel instead of covering it');
assert.doesNotMatch(miniHtml, /class="track"/, 'Mini must not render the redundant horizontal progress bar');
assert.doesNotMatch(miniHtml, /progressPercent/, 'Mini percent must use the reward contract field');
assert.doesNotMatch(miniHtml, /global\?\.activeSeconds/, 'Mini status must use the global summary contract fields');
assert.match(miniHtml, /id="equalsValue"/, 'Mini must show counted equals');
assert.match(miniHtml, /id="workValue"/, 'Mini must show real active work time');
