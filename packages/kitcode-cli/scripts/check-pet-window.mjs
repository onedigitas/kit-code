assert.match(companion, /`\$\{apiBase\}\/pet`/, 'Connected Pet must load from the tracker origin');
assert.doesNotMatch(read('src/cors.mjs'), /DEFAULT_ALLOWED_ORIGINS[\s\S]*['"]null['"]/, 'Companion fix must not trust every null origin');
assert.match(companion, /const miniWidth = 320/, 'Mini host must keep the metric panel compact horizontally');
assert.match(companion, /const miniHeight = 110/, 'Mini host must reserve a separate floating-control footer');
