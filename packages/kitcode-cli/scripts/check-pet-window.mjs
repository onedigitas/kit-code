assert.match(controls, /left: 50%/, 'Shared mode switcher must be horizontally centered');
assert.match(controls, /bottom: 4px/, 'Shared mode switcher must sit at the bottom');
assert.match(controls, /width: 58px/, 'Shared mode switcher must remain compact');
assert.match(controls, /class="companion-control-dock"/, 'Mode switcher and close must share one floating dock');
assert.match(controls, /transform: translateX\(-29px\)/, 'View switch itself must remain centered while close sits to its right');
